const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const emptyDraft = () => ({ name: '', email: '', password: '', birthDate: '', gender: 'female', city: '', phone: '', profession: '', bio: '', photos: [] });
const source = fs.readFileSync(path.join(__dirname, '../src/features/agents/csv.ts'), 'utf8');
const output = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports: output, require: () => ({ emptyDraft }) });
const { csvText, templateRows, parseUsersCsv, exportUserRow, selectedUserExportRows, CSV_EXPORT_FIELDS, CSV_TEMPLATE_FIELDS } = output;
const draft = { ...emptyDraft(), name: 'रानी, "Test"', email: 'user@example.com', password: ' @Keep,Password" ', birthDate: '2001-01-02', city: 'Delhi', phone: '+919876543210', profession: 'Teacher', bio: 'About them\nSecond line', photos: ['data:image/jpeg;base64,AQID', 'data:image/png;base64,BAUG'] };
const template = templateRows([draft]);
assert.equal(template[0].length, template[1].length);
const restored = parseUsersCsv(csvText(template))[0];
for (const key of ['name', 'email', 'password', 'birthDate', 'gender', 'city', 'phone', 'profession', 'bio']) assert.equal(restored[key], draft[key], key);
assert.equal(restored.photos.length, 2);
const user = { ...draft, id: 'generated-user-id', status: 'active', onboardingCompleted: false, createdAt: '2026-11-18T00:00:00.000Z' };
const details = exportUserRow(user);
assert.equal(details.length, CSV_EXPORT_FIELDS.length);
assert.equal(details[CSV_EXPORT_FIELDS.indexOf('accountId')], user.id);
assert.equal(details[CSV_EXPORT_FIELDS.indexOf('phone')], draft.phone);
assert.equal(details[CSV_EXPORT_FIELDS.indexOf('onboarding')], 'User to complete on login');
const reimported = parseUsersCsv(csvText([[...CSV_EXPORT_FIELDS], details]))[0];
assert(!('id' in reimported)); assert(!('status' in reimported)); assert(!('onboardingCompleted' in reimported));
const storedUser = { ...user }; delete storedUser.password;
assert.equal(exportUserRow(storedUser)[CSV_EXPORT_FIELDS.indexOf('password')], '', 'Historical export never invents or exposes a stored password');
const sample = templateRows([emptyDraft()]);
assert.equal(sample[0].length, CSV_TEMPLATE_FIELDS.length);
assert.equal(sample.length, 1, 'A blank template contains headers only, never a different sample user');
assert(!csvText(sample).includes('Example User'));
assert.throws(() => parseUsersCsv(csvText(sample)), /Import between/);
const selectedRows = selectedUserExportRows(user, user.id);
assert.equal(selectedRows[1][CSV_EXPORT_FIELDS.indexOf('accountId')], user.id);
assert.equal(selectedRows[1][CSV_EXPORT_FIELDS.indexOf('name')], user.name);
assert.throws(() => selectedUserExportRows({ ...user, id: 'other-user', name: 'Other person' }, user.id), /does not match/);
assert.throws(() => parseUsersCsv(csvText([['name', 'name'], ['A', 'B']])), /duplicate/);
assert.throws(() => parseUsersCsv(csvText([[...CSV_TEMPLATE_FIELDS], [...template[1].slice(0, 9), 'javascript:alert(1)', '', '', '', '']])), /image data/);
console.log('Passed: populated templates, all user details, five photo columns, CSV/Unicode/newline round trips, generated-field isolation and historical password omission.');
(async () => {
  const suraj = { ...user, id: 'suraj-account', name: 'suraj dhakad', city: 'gwalior', profession: 'doctor' };
  let calls = 0;
  const rows = await output.registeredUserExportRows(async cursor => {
    calls++;
    return cursor ? { users: [{ ...user, id: 'second-account' }], nextCursor: null } : { users: [suraj], nextCursor: 'page-two' };
  });
  assert.equal(calls, 2); assert.equal(rows.length, 3);
  assert.equal(rows[1][CSV_EXPORT_FIELDS.indexOf('name')], 'suraj dhakad');
  assert.equal(rows[1][CSV_EXPORT_FIELDS.indexOf('city')], 'gwalior');
  assert.equal(rows[1][CSV_EXPORT_FIELDS.indexOf('profession')], 'doctor');
  await assert.rejects(() => output.registeredUserExportRows(async () => ({ users: [], nextCursor: null })), /No registered users/);
  await assert.rejects(() => output.registeredUserExportRows(async () => ({ users: [user], nextCursor: 'repeated' })), /could not finish/);
  console.log('Passed: registered-user CSV contains actual data rows, exports every page and never downloads a headers-only user export.');
})().catch(error => { console.error(error); process.exitCode = 1; });
