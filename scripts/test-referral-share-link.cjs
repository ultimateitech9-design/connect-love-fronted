const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const file = path.join(__dirname, '../src/features/referrals/shareInvitation.ts');
const js = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const context = { exports: {}, URL, URLSearchParams, process: { env: {} } };
vm.runInNewContext(js, context);
const { referralShareLink, referralPlayStoreLink, referralInvitationText, registrationReferralCode } = context.exports;
const code = 'b67dd47a922f18cb3f6563e6';
const sharePath = `/register?ref=${code}`;
const expected = `https://connectlove.in/invite/${code}`;
assert.equal(referralShareLink(sharePath), expected);
assert.equal(referralShareLink(`http://localhost:3009${sharePath}`), expected, 'old absolute local paths retain their referral code');
const play = new URL(referralPlayStoreLink(sharePath));
assert.equal(play.origin,'https://play.google.com');
const installPayload = play.searchParams.get('referrer');
assert.equal(new URLSearchParams(installPayload).get('ref'), code);
assert.equal(registrationReferralCode(`?referrer=${encodeURIComponent(installPayload)}`), code, 'app can forward the install payload to registration');
assert.equal(registrationReferralCode(`?ref=${code}`), code, 'existing registration links continue working');
assert.equal(registrationReferralCode(`?referrer=${encodeURIComponent(`ref=${code}&utm_source=member_referral`)}`),code,'previous Play Store links still retain attribution');
const namedCode = 'suraj-a3c729';
const namedLink = referralShareLink(`/register?ref=${namedCode}`);
assert.equal(namedLink,`https://connectlove.in/invite/${namedCode}`);
assert.equal(registrationReferralCode(new URL(referralPlayStoreLink(`/register?ref=${namedCode}`)).search),namedCode);
assert.equal(registrationReferralCode(`?ref=${namedCode}`),namedCode);
assert.equal(registrationReferralCode('?ref=suraj-abc&admin=true'),'');
assert.equal(registrationReferralCode('?ref=invalid'), '');
assert.equal(registrationReferralCode('?referrer=ref%3Dinvalid'), '');
assert.equal(referralShareLink('/register?ref=bad%26id%3Devil'), 'https://connectlove.in/register');
assert.equal(referralPlayStoreLink('/register?ref=bad%26id%3Devil'), 'https://play.google.com/store/apps/details?id=com.connectlove');
const text = referralInvitationText(expected);
assert.equal(text, `Join me on Connect Love! Download the app and register using my link to get a ₹100 reward.\n\n${expected}`);
assert(text.endsWith(`\n\n${expected}`));
assert.equal((text.match(/https:\/\//g) || []).length, 1);
assert(!text.includes('localhost'));
const maleText = referralInvitationText(expected, 5000);
assert.equal(maleText, `Join me on Connect Love! Download the app and register using my link to get a ₹50 reward.\n\n${expected}`);
assert(!maleText.includes('₹100'));
assert(!text.includes('₹50'));
assert(!/\b(boy|boys|girl|girls|men|women|male|female)\b/i.test(text + maleText));
console.log('PASS: direct Play Store links, encoded install attribution, registration payload parsing, invalid-code rejection and one complete message + link payload.');
